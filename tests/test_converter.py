from __future__ import annotations

from itertools import product

import pytest

from app.converter import DIALECTS, ConversionError, convert_sql


@pytest.mark.parametrize("source,target", product(DIALECTS, repeat=2))
def test_every_dialect_pair_converts_basic_select(source: str, target: str) -> None:
    result = convert_sql(
        "SELECT id, name FROM users WHERE status = 1",
        source,
        target,
        pretty=True,
    )

    assert result.statement_count == 1
    assert "SELECT" in result.sql
    assert "FROM users" in result.sql
    assert result.elapsed_ms >= 1


def test_mysql_limit_becomes_oracle_fetch() -> None:
    result = convert_sql("SELECT * FROM users LIMIT 10;", "mysql", "oracle")
    assert "FETCH FIRST 10 ROWS ONLY" in result.sql
    assert "LIMIT" not in result.sql


def test_db2_fetch_becomes_mysql_limit() -> None:
    result = convert_sql(
        "SELECT * FROM users FETCH FIRST 5 ROWS ONLY;", "db2", "mysql"
    )
    assert "LIMIT 5" in result.sql
    assert "FETCH FIRST" not in result.sql


def test_db2_current_date_and_isolation_suffix() -> None:
    result = convert_sql(
        "SELECT CURRENT DATE AS d FROM users FETCH FIRST 5 ROWS ONLY WITH UR;",
        "db2",
        "dameng",
    )
    assert "CURRENT_DATE" in result.sql.upper()
    assert "WITH UR" not in result.sql.upper()
    assert any("隔离级别" in note for note in result.notes)


def test_mysql_date_functions_become_oracle_syntax() -> None:
    result = convert_sql(
        "SELECT NOW(), DATE_FORMAT(created_at, '%Y-%m-%d'), "
        "DATE_SUB(NOW(), INTERVAL 30 DAY) FROM users;",
        "mysql",
        "oracle",
    )
    upper = result.sql.upper()
    assert "NOW()" not in upper
    assert "DATE_FORMAT" not in upper
    assert "DATE_SUB" not in upper
    assert "CURRENT_TIMESTAMP" in upper
    assert "TO_CHAR" in upper
    assert "INTERVAL '30' DAY" in upper


def test_oracle_nvl_becomes_postgres_coalesce() -> None:
    result = convert_sql("SELECT NVL(amount, 0) FROM orders;", "oracle", "postgres")
    assert "COALESCE(amount, 0)" in result.sql


def test_simple_oracle_rownum_becomes_mysql_limit() -> None:
    result = convert_sql(
        "SELECT * FROM users WHERE ROWNUM <= 10;", "oracle", "mysql"
    )
    assert "LIMIT 10" in result.sql
    assert "ROWNUM" not in result.sql.upper()
    assert any("ROWNUM" in note for note in result.notes)


def test_mysql_auto_increment_becomes_oracle_identity() -> None:
    result = convert_sql(
        "CREATE TABLE t (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(20));",
        "mysql",
        "oracle",
    )
    assert "GENERATED BY DEFAULT AS IDENTITY" in result.sql
    assert "AUTO_INCREMENT" not in result.sql.upper()
    assert "NUMBER(19)" in result.sql


def test_oracle_identity_becomes_mysql_auto_increment() -> None:
    result = convert_sql(
        "CREATE TABLE t (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);",
        "oracle",
        "mysql",
    )
    assert "BIGINT AUTO_INCREMENT" in result.sql
    assert "GENERATED BY DEFAULT AS IDENTITY" not in result.sql.upper()


def test_mysql_tinyint_boolean_maps_to_oracle_number_one() -> None:
    result = convert_sql(
        "CREATE TABLE t (active TINYINT(1) DEFAULT 1);", "mysql", "oracle"
    )
    assert "NUMBER(1)" in result.sql
    assert "NUMBER(1)(1)" not in result.sql


def test_db2_date_arithmetic_uses_labeled_duration() -> None:
    result = convert_sql(
        "SELECT CURRENT TIMESTAMP + 2 HOURS FROM SYSIBM.SYSDUMMY1;",
        "db2",
        "oracle",
    )
    assert "CURRENT TIMESTAMP" not in result.sql.upper()
    assert "CURRENT_TIMESTAMP" in result.sql.upper()


def test_mysql_table_options_and_comments_are_removed() -> None:
    result = convert_sql(
        "CREATE TABLE t (id INT COMMENT '编号') ENGINE=InnoDB "
        "DEFAULT CHARSET=utf8mb4 COMMENT='用户表';",
        "mysql",
        "oracle",
    )
    assert "ENGINE" not in result.sql.upper()
    assert "CHARSET" not in result.sql.upper()
    assert " COMMENT '" not in result.sql.upper()
    assert any("表级选项" in note for note in result.notes)
    assert any("字段注释" in note for note in result.notes)


def test_oracle_listagg_becomes_mysql_group_concat() -> None:
    result = convert_sql(
        "SELECT LISTAGG(name, ',') WITHIN GROUP (ORDER BY id) FROM users;",
        "oracle",
        "mysql",
    )
    assert "GROUP_CONCAT" in result.sql.upper()
    assert "LISTAGG" not in result.sql.upper()
    assert "ORDER BY" in result.sql.upper()


def test_db2_offset_uses_fetch_next() -> None:
    result = convert_sql("SELECT * FROM t LIMIT 5 OFFSET 10;", "mysql", "db2")
    assert "OFFSET 10 ROWS" in result.sql
    assert "FETCH NEXT 5 ROWS ONLY" in result.sql


def test_mysql_concat_to_oracle_uses_pipe_operator() -> None:
    result = convert_sql("SELECT CONCAT(a, b, c) FROM t;", "mysql", "oracle")
    assert "a || b || c" in result.sql
    assert "CONCAT(a, b, c)" not in result.sql


def test_group_concat_becomes_listagg() -> None:
    result = convert_sql(
        "SELECT GROUP_CONCAT(name SEPARATOR ',') FROM users;", "mysql", "oracle"
    )
    assert "LISTAGG(name, ',')" in result.sql


def test_mysql_upsert_emits_review_note() -> None:
    result = convert_sql(
        "INSERT INTO t (id, name) VALUES (1, 'a') "
        "ON DUPLICATE KEY UPDATE name = 'b';",
        "mysql",
        "oracle",
    )
    assert any("ON DUPLICATE KEY UPDATE" in note for note in result.notes)


def test_oracle_from_less_select_gets_dual() -> None:
    result = convert_sql("SELECT 1;", "oracle", "oracle")
    assert "FROM DUAL" in result.sql


def test_db2_from_less_select_gets_sysdummy() -> None:
    result = convert_sql("SELECT 1;", "mysql", "db2")
    assert "FROM SYSIBM.SYSDUMMY1" in result.sql


def test_oracle_dual_becomes_db2_sysdummy() -> None:
    result = convert_sql("SELECT 1 FROM DUAL;", "oracle", "db2")
    assert "SYSIBM.SYSDUMMY1" in result.sql
    assert "FROM DUAL" not in result.sql


def test_db2_sysdummy_becomes_oracle_dual() -> None:
    result = convert_sql("SELECT 1 FROM SYSIBM.SYSDUMMY1;", "db2", "oracle")
    assert "FROM DUAL" in result.sql
    assert "SYSIBM.SYSDUMMY1" not in result.sql


def test_dual_is_removed_for_postgres() -> None:
    result = convert_sql("SELECT 1 FROM DUAL;", "oracle", "postgres")
    assert "DUAL" not in result.sql
    assert "FROM" not in result.sql


def test_postgres_serial_becomes_oracle_identity() -> None:
    result = convert_sql(
        "CREATE TABLE t (id BIGSERIAL PRIMARY KEY);", "postgres", "oracle"
    )
    assert "NUMBER(19)" in result.sql
    assert "GENERATED BY DEFAULT AS IDENTITY" in result.sql
    assert "BIGSERIAL" not in result.sql
    assert result.sql.index("GENERATED BY DEFAULT") < result.sql.index("PRIMARY KEY")


def test_dameng_limit_becomes_db2_fetch() -> None:
    result = convert_sql("SELECT * FROM users LIMIT 8;", "dameng", "db2")
    assert "FETCH FIRST 8 ROWS ONLY" in result.sql


def test_multiple_statements_are_converted_separately() -> None:
    result = convert_sql(
        "SELECT 1; UPDATE users SET name = 'x' WHERE id = 1;", "mysql", "oracle"
    )
    assert result.statement_count == 2
    assert result.sql.count(";") == 1
    assert "UPDATE users" in result.sql


def test_parse_error_has_line_and_column() -> None:
    with pytest.raises(ConversionError) as exc_info:
        convert_sql("SELECT FROM WHERE", "mysql", "oracle")

    error = exc_info.value
    assert error.code == "PARSE_ERROR"
    assert error.line == 1
    assert error.column


def test_empty_sql_raises() -> None:
    with pytest.raises(ConversionError) as exc_info:
        convert_sql("   ", "mysql", "oracle")

    assert exc_info.value.code == "EMPTY_SQL"


def test_compact_output_has_no_pretty_newlines() -> None:
    result = convert_sql(
        "SELECT id, name FROM users WHERE id = 1;", "mysql", "postgres", pretty=False
    )
    assert "\n" not in result.sql
    assert any("美化格式" in note for note in result.notes)
