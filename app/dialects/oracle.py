"""Oracle output refinements used by SQLVIP.

SQLGlot's Oracle dialect is excellent for Oracle-native input, but when the
source is MySQL/PostgreSQL its default type mapping keeps several non-Oracle
types (for example BIGINT, BOOLEAN and DATETIME). SQLVIP replaces the registered
``oracle`` dialect with this thin subclass so generated Oracle SQL is directly
usable on Oracle 12c/19c.
"""

from __future__ import annotations

import typing as t

from sqlglot import exp
from sqlglot.dialects.oracle import Oracle as OracleDialect


def _date_arithmetic_sql(
    operator: str,
) -> t.Callable[[OracleDialect.Generator, exp.DateAdd | exp.DateSub], str]:
    """Render MySQL/ANSI date arithmetic with Oracle INTERVAL syntax."""

    def _render(
        self: OracleDialect.Generator, expression: exp.DateAdd | exp.DateSub
    ) -> str:
        this = self.sql(expression, "this")
        value = expression.expression
        unit = (expression.args.get("unit") or exp.var("DAY")).name.upper()

        if isinstance(value, exp.Literal):
            interval = f"INTERVAL '{value.this}' {unit}"
        else:
            interval = f"NUMTODSINTERVAL({self.sql(value)}, '{unit}')"

        return f"{this} {operator} {interval}"

    return _render


class Oracle(OracleDialect):
    """Oracle dialect with migration-friendly type and boolean output."""

    class Generator(OracleDialect.Generator):
        TYPE_MAPPING = {
            **OracleDialect.Generator.TYPE_MAPPING,
            exp.DataType.Type.TINYINT: "NUMBER(3)",
            exp.DataType.Type.SMALLINT: "NUMBER(5)",
            exp.DataType.Type.INT: "NUMBER(10)",
            exp.DataType.Type.BIGINT: "NUMBER(19)",
            exp.DataType.Type.MEDIUMINT: "NUMBER(7)",
            exp.DataType.Type.DECIMAL: "NUMBER",
            exp.DataType.Type.DOUBLE: "BINARY_DOUBLE",
            exp.DataType.Type.FLOAT: "BINARY_FLOAT",
            exp.DataType.Type.BOOLEAN: "NUMBER(1)",
            exp.DataType.Type.DATETIME: "TIMESTAMP",
            exp.DataType.Type.TIMESTAMPTZ: "TIMESTAMP WITH TIME ZONE",
            exp.DataType.Type.TIMESTAMPLTZ: "TIMESTAMP WITH LOCAL TIME ZONE",
            exp.DataType.Type.TEXT: "CLOB",
            exp.DataType.Type.VARCHAR: "VARCHAR2",
            exp.DataType.Type.NVARCHAR: "NVARCHAR2",
            exp.DataType.Type.BINARY: "BLOB",
            exp.DataType.Type.VARBINARY: "BLOB",
            exp.DataType.Type.UUID: "VARCHAR2(36)",
        }

        TRANSFORMS = {
            **OracleDialect.Generator.TRANSFORMS,
            # Oracle before 23c has no SQL boolean literals. NUMBER(1) is the
            # conventional portable representation.
            exp.Boolean: lambda self, e: "1" if e.this else "0",
            exp.DateAdd: _date_arithmetic_sql("+"),
            exp.DateSub: _date_arithmetic_sql("-"),
        }

        def autoincrementcolumnconstraint_sql(
            self, _: exp.AutoIncrementColumnConstraint
        ) -> str:
            # Oracle 12c+ identity column. Older releases need a sequence and
            # trigger; the API adds a note when this rewrite is used.
            return "GENERATED BY DEFAULT AS IDENTITY"

        def groupconcat_sql(self, expression: exp.GroupConcat) -> str:
            this = self.sql(expression, "this")
            separator = self.sql(expression, "separator") or "','"
            return f"LISTAGG({this}, {separator})"


# SQLGlot resolves dialects by registry key. Replacing the built-in key keeps
# ``read="oracle"`` / ``write="oracle"`` working while applying the refinements.
from sqlglot.dialects.dialect import Dialect  # noqa: E402

Dialect._classes["oracle"] = Oracle

__all__ = ["Oracle"]
